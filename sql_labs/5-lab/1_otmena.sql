Отмена бронирования

1.1 Успешная отмена (COMMIT)

-- Посмотрим, какие есть бронирования
SELECT * FROM BOOKING LIMIT 5;

-- Начинаем транзакцию
BEGIN;

-- Меняем статус бронирования с "активно" на "отменено"
UPDATE BOOKING 
SET СТАТУС = 'отменено' 
WHERE BOOKING_ID = 1;

-- Проверяем, что изменилось
SELECT * FROM BOOKING WHERE BOOKING_ID = 1;

-- Сохраняем изменения
COMMIT;

-- Ещё раз проверяем — изменения остались
SELECT * FROM BOOKING WHERE BOOKING_ID = 1;
---------------------------


1.2 Ошибка внутри транзакции (ROLLBACK)

-- Начинаем транзакцию
BEGIN;

-- Обновляем статус
UPDATE BOOKING SET СТАТУС = 'активно' WHERE BOOKING_ID = 1;

-- Симулируем ошибку (например, деление на ноль — такого поля нет)
SELECT 1/0; -- типа обновляли обновляли и в одном из обновлений получилась ошибка

-- Сюда мы не попадём, потому что выше ошибка
COMMIT;-- будет ролбэк

-- Выходим из транзакции (откатываем всё)
ROLLBACK;

-- Проверяем: статус не изменился (остался "отменено")
SELECT * FROM BOOKING WHERE BOOKING_ID = 1;
-----------------------------


1.3 Частичный откат (SAVEPOINT)
-- Начинаем транзакцию
BEGIN;

-- Шаг 1: Меняем статус бронирования
UPDATE BOOKING SET СТАТУС = 'активно' WHERE BOOKING_ID = 1;

-- Создаём точку сохранения
SAVEPOINT after_first_update;

-- Шаг 2: Добавляем новое бронирование (с ошибкой)
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (999999, 1, 1, '2026-06-01', '10:00:00', '12:00:00', 'активно');

-- Ошибки нет? Тогда удалим точку и закоммитим
-- А если ошибка — откатимся до точки

-- Откатываемся только до точки (INSERT отменится, UPDATE останется)
ROLLBACK TO SAVEPOINT after_first_update;

-- Фиксируем транзакцию
COMMIT;

-- Проверяем: статус стал "активно", бронирования 999999 нет
SELECT * FROM BOOKING WHERE BOOKING_ID = 1;
SELECT * FROM BOOKING WHERE BOOKING_ID = 999999;
----------------------------


