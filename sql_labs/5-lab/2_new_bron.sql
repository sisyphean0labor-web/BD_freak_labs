Создание нового бронирования


2.1 Успешное создание (COMMIT)

-- Посмотрим текущие бронирования
SELECT * FROM BOOKING ORDER BY BOOKING_ID DESC LIMIT 5;

-- Начинаем транзакцию
BEGIN;

-- Добавляем новое бронирование
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (1000005, 2, 1, '2026-07-15', '11:00:00', '13:00:00', 'активно');

-- Проверяем, что добавилось
SELECT * FROM BOOKING WHERE BOOKING_ID = 1000005;

-- Фиксируем изменения
COMMIT;

-- Проверяем ещё раз
SELECT * FROM BOOKING WHERE BOOKING_ID = 1000005;
---------------------------


2.2 Ошибка внутри транзакции (ROLLBACK)

-- Начинаем транзакцию
BEGIN;

-- Добавляем бронирование
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (1000006, 2, 1, '2026-07-16', '14:00:00', '16:00:00', 'активно');

-- Симулируем ошибку (вставляем дубликат с тем же ID)
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (1000006, 2, 1, '2026-07-16', '14:00:00', '16:00:00', 'активно');

-- Сюда не дойдём из-за ошибки
COMMIT;-- будет ролбэк

-- Откатываем всё
ROLLBACK;

-- Проверяем: бронирования 1000006 нет
SELECT * FROM BOOKING WHERE BOOKING_ID = 1000006;
-------------------------------


2.3 Частичный откат (SAVEPOINT)

-- Начинаем транзакцию
BEGIN;

-- Шаг 1: Добавляем первое бронирование
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (1000007, 3, 2, '2026-07-17', '09:00:00', '10:00:00', 'активно');

-- Создаём точку сохранения
SAVEPOINT after_first_insert;

-- Шаг 2: Добавляем второе бронирование (для того же пользователя)
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (1000008, 3, 3, '2026-07-18', '12:00:00', '14:00:00', 'активно');

-- Решили, что второе бронирование не нужно
-- Откатываемся до точки (второе бронирование отменится, первое останется)
ROLLBACK TO SAVEPOINT after_first_insert;

-- Фиксируем транзакцию
COMMIT;

-- Проверяем: бронирование 1000007 есть, 1000008 нет
SELECT * FROM BOOKING WHERE BOOKING_ID = 1000007;
SELECT * FROM BOOKING WHERE BOOKING_ID = 1000008;
-------------------------------------------


