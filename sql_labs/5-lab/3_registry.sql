Регистрация нового пользователя + первое бронирование
    Бизнес-правило: Когда приходит новый пользователь, нужно:
        Зарегистрировать его (добавить в таблицу USERS)
        Создать его первое бронирование (добавить в BOOKING)
        Если что-то пошло не так — откатить всё


3.1 Успешная регистрация и бронирование (COMMIT)

-- Посмотрим, сколько сейчас пользователей
SELECT COUNT(*) FROM USERS;

-- Посмотрим последние бронирования
SELECT * FROM BOOKING ORDER BY BOOKING_ID DESC LIMIT 5;

-- Начинаем транзакцию
BEGIN;

-- 1. Добавляем нового пользователя
INSERT INTO USERS (USER_ID, ИМЯ, EMAIL, ТЕЛЕФОН, ДАТА_РЕГИСТРАЦИИ, IS_ADMIN)
VALUES (10, 'НовыйКлиент', 'new@example.com', '+7 (999) 000-00-00', '2026-05-24', FALSE);

-- 2. Добавляем бронирование для этого пользователя
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (2000001, 10, 1, '2026-06-10', '15:00:00', '17:00:00', 'активно');

-- Проверяем, что всё добавилось
SELECT * FROM USERS WHERE USER_ID = 10;
SELECT * FROM BOOKING WHERE USER_ID = 10;

-- Фиксируем изменения
COMMIT;

-- Финальная проверка
SELECT * FROM USERS WHERE USER_ID = 10;
SELECT * FROM BOOKING WHERE USER_ID = 10;
----------------------------------------


3.2 Ошибка внутри транзакции (ROLLBACK)

-- Начинаем транзакцию
BEGIN;

-- 1. Добавляем пользователя
INSERT INTO USERS (USER_ID, ИМЯ, EMAIL, ТЕЛЕФОН, ДАТА_РЕГИСТРАЦИИ, IS_ADMIN)
VALUES (11, 'Ошибочный', 'error@example.com', '+7 (999) 111-11-11', '2026-05-24', FALSE);

-- 2. Добавляем бронирование с ошибкой (неправильный SPACE_ID = 999)
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (2000002, 11, 999, '2026-06-11', '12:00:00', '13:00:00', 'активно');
-- ОШИБКА! Места с ID=999 не существует

-- Сюда не дойдём
COMMIT;-- будет ролбэк

-- Откатываем всё
ROLLBACK;

-- Проверяем: пользователь НЕ добавился (транзакция откатилась полностью)
SELECT * FROM USERS WHERE USER_ID = 11;
SELECT * FROM BOOKING WHERE USER_ID = 11;
-------------------------------------------


3.3 Частичный откат (SAVEPOINT)

-- Начинаем транзакцию
BEGIN;

-- Шаг 1: Добавляем пользователя
INSERT INTO USERS (USER_ID, ИМЯ, EMAIL, ТЕЛЕФОН, ДАТА_РЕГИСТРАЦИИ, IS_ADMIN)
VALUES (12, 'Частичный', 'partial@example.com', '+7 (999) 222-22-22', '2026-05-24', FALSE);

-- Создаём точку сохранения
SAVEPOINT after_user_created;

-- Шаг 2: Пытаемся добавить бронирование (с ошибкой)
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (2000003, 12, 999, '2026-06-12', '14:00:00', '15:00:00', 'активно');
-- ОШИБКА! Места с ID=999 нет

-- Откатываемся до точки (бронирование отменится, пользователь останется)
ROLLBACK TO SAVEPOINT after_user_created;

-- Теперь добавим правильное бронирование
INSERT INTO BOOKING (BOOKING_ID, USER_ID, SPACE_ID, ДАТА_БРОНИРОВАНИЯ, ВРЕМЯ_НАЧАЛА, ВРЕМЯ_КОНЦА, СТАТУС)
VALUES (2000003, 12, 1, '2026-06-12', '14:00:00', '15:00:00', 'активно');

-- Фиксируем транзакцию
COMMIT;

-- Проверяем: пользователь 12 есть, бронирование 2000003 есть
SELECT * FROM USERS WHERE USER_ID = 12;
SELECT * FROM BOOKING WHERE USER_ID = 12;
