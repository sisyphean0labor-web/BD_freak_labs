Запрос 4. Текстовый поиск (LIKE)

-- ========================================
-- 1. БЕЗ ИНДЕКСА
-- ========================================
EXPLAIN ANALYZE 
SELECT * FROM SPACE 
-- Ищем в таблице мест
WHERE НАЗВАНИЕ_МЕСТА LIKE 'Переговорка%';
-- LIKE 'Переговорка%' - ищет все названия, начинающиеся с "Переговорка"
-- % - любое количество любых символов после

-- ========================================
-- 2. СОЗДАЁМ ИНДЕКС ДЛЯ ТЕКСТОВОГО ПОИСКА
-- ========================================
CREATE INDEX idx_space_name 
ON SPACE (НАЗВАНИЕ_МЕСТА);
-- Обычный B-tree индекс для текста
-- Помогает только для поиска по ПРЕФИКСУ (слово% НЕ %слово)

-- ========================================
-- 3. С ИНДЕКСОМ
-- ========================================
EXPLAIN ANALYZE 
SELECT * FROM SPACE 
WHERE НАЗВАНИЕ_МЕСТА LIKE 'Переговорка%';

-- ========================================
-- 4. УДАЛЯЕМ ИНДЕКС
-- ========================================
DROP INDEX idx_space_name;

Индекс работает: для LIKE 'слово%' (поиск по началу слова) ✅
Индекс НЕ работает: для LIKE '%слово%' (процент в начале) ❌